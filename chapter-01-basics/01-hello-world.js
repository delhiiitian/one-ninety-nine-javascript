// 1.1 Hello, World: running your first JavaScript program
// Run: node chapter-01-basics/01-hello-world.js

// console.log prints a message to the terminal (or the browser console).
console.log("Hello, World!");

// You can print several values at once. They are separated by spaces.
console.log("JavaScript runs in", "browsers", "and", "Node.js");

// Statements run from top to bottom, one after another.
console.log("Step 1: wake up");
console.log("Step 2: make coffee");
console.log("Step 3: write code");

/*
  This is a multi-line comment.
  JavaScript ignores comments; they are notes for humans.
*/

// Other console helpers you will use every day:
console.error("This goes to the error stream (shown in red in many terminals)");
console.table([
  { language: "JavaScript", year: 1995 },
  { language: "Python", year: 1991 },
]);
